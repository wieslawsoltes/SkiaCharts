namespace SkiaCharts.Core.Axes;

/// <summary>
/// Defines the position of an axis on a chart.
/// </summary>
public enum AxisPosition
{
    /// <summary>
    /// Left side of the chart (vertical axis).
    /// </summary>
    Left,

    /// <summary>
    /// Right side of the chart (vertical axis).
    /// </summary>
    Right,

    /// <summary>
    /// Bottom of the chart (horizontal axis).
    /// </summary>
    Bottom,

    /// <summary>
    /// Top of the chart (horizontal axis).
    /// </summary>
    Top
}
